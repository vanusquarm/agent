using Microsoft.AspNetCore.Mvc;

namespace Finacle.Infrastructure.Logging
{
    public class CustomProblemDetails : ProblemDetails
    {
        public string ResponseCode { get; set; }
        public bool IsSuccess { get; set; }
        public object FinacleData { get; set; }
        public string transactionReference { get; set; }

        /// <summary>
        /// Custom Class for formatting the failure response on the API according to  https://tools.ietf.org/html/rfc7807
        /// </summary>
        /// <param name="detail">A human-readable explanation specific to this occurrence of the problem</param>
        /// <param name="ResponseCode">Response code for further </param>
        /// <param name="title"> A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence of the problem, except for purposes of localization(e.g., using proactive content negotiation; see[RFC7231], Section 3.4).</param>
        /// <param name="status">The HTTP status code([RFC7231], Section 6) generated by the origin server for this occurrence of the problem</param>     
        /// <returns></returns>
        public static CustomProblemDetails FailureResponse(string detail, string ResponseCode, string title, int status, string transactionReference = null)
        {
            return FailureResponse(detail, ResponseCode, title, status, $"https://developer.mozilla.org/en-US/docs/Web/HTTP/Status/{status}", transactionReference);
        }


        /// <summary>
        /// Custom Class for formatting the failure response on the API according to  https://tools.ietf.org/html/rfc7807
        /// </summary>
        /// <param name="detail">A human-readable explanation specific to this occurrence of the problem</param>
        /// <param name="ResponseCode">Response code for further </param>
        /// <param name="title"> A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence of the problem, except for purposes of localization(e.g., using proactive content negotiation; see[RFC7231], Section 3.4).</param>
        /// <param name="status">The HTTP status code([RFC7231], Section 6) generated by the origin server for this occurrence of the problem</param>
        /// <param name="type"> A URI reference [RFC3986] that identifies the problem type.This specification encourages that, when dereferenced, it provide human-readable documentation for the problem type (e.g., using HTML [W3C.REC-html5-20141028]).  When this member is not present, its value is assumed to be about:blank</param>
        /// <returns></returns>
        public static CustomProblemDetails FailureResponse(string detail, string ResponseCode, string title, int status, string type, string transactionReference = null)
        {
            return new CustomProblemDetails
            {
                Type = type,
                Title = title,
                Status = status,
                Detail = detail,
                ResponseCode = ResponseCode,
                Instance = null,
                Extensions = null,
                transactionReference = transactionReference
            };
        }
    }
}
